function sayGoodbye(){
    const name = prompt("Hello, what is your name?")
    if (name != null){
        window.alert("Goodbye "+name+"! Thank you for visiting my site!")
    }
}

function sayHello() {
    const name = prompt("Hello, what is your name?");
    if (name != null) {
        window.alert("Nice to meet you " + name + "! Thank you for visiting my site!");
    }
}